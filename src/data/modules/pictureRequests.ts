/**
 * Every picture requested for a lesson page, and the pages it is for. The picture chat draws
 * (status `requested` → `drawn`, with the gallery demos that show it); the lesson chat puts it on
 * the pages (`drawn` → `placed`). `pictureRequests.test.ts` checks the pages and gallery ids
 * exist and that a placed picture is on every page it names. Brief: docs/RENDERINGS_BRIEF.md.
 */
export type PictureStatus = 'requested' | 'drawn' | 'placed';

export interface PictureRequest {
  /** R.. for K–6 pages, G.. for the planned Grade 7 and 8 skills, D.. for the K–6 diagram review. */
  id: string;
  /** What to draw, in a few words. */
  what: string;
  /** The picture kind or explore figure (`representation.kind` or `figure.kind`). */
  kind: string;
  /** The page ids it is for (`m.4.decimals-intro`), or a planned skill or page id. */
  pages: string[];
  status: PictureStatus;
  /** Gallery demo ids once drawn. */
  gallery: string[];
  /** Text that shows the picture is on a page (`"inequality"`); default the kind in quotes. */
  uses?: string;
  /** What the page needs from the picture, or what the page still needs. */
  notes?: string;
}

