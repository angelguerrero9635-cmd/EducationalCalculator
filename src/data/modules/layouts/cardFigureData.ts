/**
 * A constellation's stars as seen looking up (north up, east on the left), projected onto the
 * plane touching the sky at the pattern's middle (gnomonic), in degrees: [x, y down, magnitude].
 */
export function starChart(name: Constellation): {
  points: [number, number, number][];
  lines: [number, number][];
} {
  const { stars, lines } = CONSTELLATIONS[name];
  const rad = Math.PI / 180;
  const ra = stars.map(([h]) => h * 15 * rad);
  const dec = stars.map(([, d]) => d * rad);
  const ra0 = ra.reduce((s, x) => s + x, 0) / ra.length;
  const dec0 = dec.reduce((s, x) => s + x, 0) / dec.length;
  const points = stars.map((st, i) => {
    const dRa = ra[i]! - ra0;
    const d = dec[i]!;
    const cosc = Math.sin(dec0) * Math.sin(d) + Math.cos(dec0) * Math.cos(d) * Math.cos(dRa);
    const x = (Math.cos(d) * Math.sin(dRa)) / cosc;
    const y = (Math.cos(dec0) * Math.sin(d) - Math.sin(dec0) * Math.cos(d) * Math.cos(dRa)) / cosc;
    // East (larger right ascension) is on the left of a chart of the sky overhead.
    return [-x / rad, -y / rad, st[2]] as [number, number, number];
  });
  return { points, lines };
}

