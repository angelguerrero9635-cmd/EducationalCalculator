// ── Checks ──

/** What is wrong with a round-3 card figure (the drawing would not fit its data), if anything. */
export function cardFigureProblems(f: CardFigure): string[] {
  const out: string[] = [];
  switch (f.kind) {
    case 'strobe':
      out.push(...strobeCardProblems(f));
      break;
    case 'dotPlot': {
      if (f.values.length < 2 || f.values.length > 12)
        out.push(`dot plot of ${f.values.length} values (2 to 12 fit)`);
      if (f.values.some((v) => !Number.isFinite(v))) out.push('dot plot value not a number');
      if (Math.min(...f.values) === Math.max(...f.values)) out.push('dot plot values all equal');
      break;
    }
    case 'map': {
      const v = MAP_VIEWS[f.area];
      if (!f.pin && !f.region) out.push('map with neither a pin nor a region');
      if (f.pin) {
        const [lon, lat] = f.pin;
        const x = viewLon(f.area, lon);
        if (x < v.west || x > v.east || lat < v.south || lat > v.north)
          out.push(`pin ${lon}, ${lat} is off the ${f.area} map`);
      }
      if (f.region && !MAP_REGIONS[f.region].areas.includes(f.area))
        out.push(`region ${f.region} is not drawn on the ${f.area} map`);
      break;
    }
    case 'cell':
      if (f.highlight && !CELL_PARTS[f.type].includes(f.highlight))
        out.push(`a ${f.type} cell has no ${f.highlight} to outline`);
      if (f.highlight && f.shape && f.shape !== (f.type === 'plant' ? 'box' : 'round'))
        out.push('a highlighted cell is drawn box (plant) or round (animal)');
      break;
    case 'stars':
      if (!CONSTELLATIONS[f.constellation]) out.push(`no star chart for ${f.constellation}`);
      break;
  }
  return out;
}
